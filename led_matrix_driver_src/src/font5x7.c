/* ================================================================
 *  接口实现
 * ================================================================ */

const uint8_t *font5x7_get_cols(char c)
{
    unsigned idx = (unsigned char)c - FONT5X7_FIRST_CHAR;
    if (idx >= FONT5X7_CHAR_COUNT)
        idx = 0;                    /* 超范围 → 返回空格 */
    return font_data[idx];
}

int font5x7_get_rows(char c, uint8_t rows_out[7])
{
    const uint8_t *cols = font5x7_get_cols(c);

    for (int y = 0; y < FONT5X7_HEIGHT; y++) {
        uint8_t row = 0;
        for (int x = 0; x < FONT5X7_WIDTH; x++) {
            if (cols[x] & (1u << y))
                row |= (1u << (4 - x));   /* bit4 = 最左列 (col 0) */
        }
        rows_out[y] = row;
    }
    return 0;
}

int font5x7_text_to_cols_ex(const char *text, uint8_t *out_cols,
                             int max_cols, int spacing)
{
    if (!text || !out_cols || max_cols <= 0)
        return 0;

    int n = 0;
    for (const char *p = text; *p; p++) {
        /* 字符间距 (第一个字符前不加) */
        if (p != text) {
            for (int s = 0; s < spacing && n < max_cols; s++)
                out_cols[n++] = 0x00;
        }

        const uint8_t *cols = font5x7_get_cols(*p);
        for (int i = 0; i < FONT5X7_WIDTH && n < max_cols; i++)
            out_cols[n++] = cols[i];
    }
    return n;
}

int font5x7_text_to_cols(const char *text, uint8_t *out_cols, int max_cols)
{
    return font5x7_text_to_cols_ex(text, out_cols, max_cols, FONT5X7_SPACING);
}

int font5x7_text_width_ex(const char *text, int spacing)
{
    if (!text || !*text)
        return 0;

    int len = (int)strlen(text);
    return len * FONT5X7_WIDTH + (len - 1) * spacing;
}

int font5x7_text_width(const char *text)
{
    return font5x7_text_width_ex(text, FONT5X7_SPACING);
}

int font5x7_glyph_count(void)
{
    return FONT5X7_CHAR_COUNT;
}
